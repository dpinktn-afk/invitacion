-- Supabase: tabla para las confirmaciones de la boda
create table if not exists public.invitados (
  id bigint generated by default as identity primary key,
  nombre text not null,
  contacto text not null,
  asistencia text not null check (asistencia in ('confirmed', 'pending', 'declined')),
  personas integer not null default 1 check (personas between 1 and 10),
  mensaje text,
  created_at timestamptz not null default now()
);

create index if not exists invitados_created_at_idx on public.invitados (created_at desc);

-- La API de Vercel usa la service_role key en el servidor.
-- Por seguridad, el cliente público NO recibe esa clave.
-- Dejamos RLS activo para evitar acceso directo anónimo desde Supabase.
alter table public.invitados enable row level security;

